#!/usr/bin/env python3
"""Generate a named, logging stub for every slot of the D3D12 DDI tables.

The slot lists and signatures come from the SDK's d3d12umddi.h through clang's
JSON AST, never from hand-written prototypes: a stub with the wrong prototype is
an ABI bug on ARM64EC, where x64 callers reach it through an entry thunk built
from that prototype. The runtime rejects NULL slots, so every table is first
filled with these stubs and the implemented slots are overwritten afterwards
(ddi_tables.c).

  gen_ddi_stubs.py --cc aarch64-w64-mingw32-clang -I... -o ddi_stubs.c
"""
import argparse
import json
import re
import subprocess
import sys

# (C struct, short name used in logs and symbols)
TABLES = [
    ('D3D12DDI_DEVICE_FUNCS_CORE_0040', 'core'),
    ('D3D12DDI_COMMAND_LIST_FUNCS_3D_0040', 'cl'),
    ('D3D12DDI_COMMAND_QUEUE_FUNCS_CORE_0001', 'queue'),
    ('D3D12DDI_EXTENDED_FEATURES_FUNCS_0021', 'ext'),
]
# Expected slot counts: a moved SDK pin must fail the build, not shift a table.
COUNTS = {'core': 96, 'cl': 58, 'queue': 7, 'ext': 4}

SOURCE = '''#define WIN32_LEAN_AND_MEAN
#include <windows.h>
#include <winddk_compat.h>
#include <d3d10umddi.h>
#include <d3d12umddi.h>
'''


def parse_ast(cc, includes, table):
    # -ast-dump-filter takes a single name, so one clang run per table.
    cmd = [cc, '-std=gnu23', '-fsyntax-only', '-x', 'c', '-', '-Xclang', '-ast-dump=json',
           '-Xclang', '-ast-dump-filter', '-Xclang', table]
    cmd += ['-I' + i for i in includes]
    out = subprocess.run(cmd, input=SOURCE, capture_output=True, text=True, check=True).stdout
    decoder = json.JSONDecoder()
    pos = 0
    while pos < len(out):
        while pos < len(out) and out[pos].isspace():
            pos += 1
        if pos >= len(out):
            break
        node, pos = decoder.raw_decode(out, pos)
        if node.get('kind') == 'RecordDecl' and node.get('name') == table and node.get('completeDefinition'):
            return [f for f in node.get('inner', []) if f['kind'] == 'FieldDecl']
    return None


def split_params(params):
    out, depth, cur = [], 0, ''
    for ch in params:
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        depth += ch in '(['
        depth -= ch in ')]'
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [] if out == ['void'] else out


def signature(field):
    """'void (*)(D3D12DDI_HDEVICE, DXGI_FORMAT, UINT *) __attribute__((stdcall))'"""
    t = field['type'].get('desugaredQualType', field['type']['qualType'])
    t = t.replace('__attribute__((stdcall))', '').strip()
    m = re.fullmatch(r'(.+?)\s*\(\*\)\((.*)\)', t)
    if not m:
        return None
    return m.group(1).strip(), split_params(m.group(2))


def declare(ptype, name):
    # Pointer-to-array/function parameters would need the name spliced inside.
    if '(*' in ptype or '[' in ptype:
        raise SystemExit(f'unsupported parameter type {ptype!r}')
    return f'{ptype} {name}'


def default_return(ret):
    if ret == 'void':
        return None
    if ret == 'HRESULT':
        return 'E_NOTIMPL'
    if ret == 'SIZE_T':
        # CalcPrivate*Size: the runtime allocates this much for the driver.
        return '64'
    if ret in ('UINT', 'INT', 'BOOL', 'UINT64', 'UINT32', 'D3D12DDI_GPU_VIRTUAL_ADDRESS'):
        return '0'
    # Struct returns (descriptor handles): zero-initialized value.
    return f'({ret}){{0}}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cc', required=True)
    ap.add_argument('-I', dest='includes', action='append', default=[])
    ap.add_argument('-o', dest='output', required=True)
    a = ap.parse_args()

    lines = [
        '/* Generated by gen_ddi_stubs.py from d3d12umddi.h -- do not edit. */',
        '#include "d3d12_umd.h"',
        '',
    ]
    for table, short in TABLES:
        fields = parse_ast(a.cc, a.includes, table)
        if fields is None:
            raise SystemExit(f'{table} not found in d3d12umddi.h')
        if len(fields) != COUNTS[short]:
            raise SystemExit(f'{table}: {len(fields)} slots, expected {COUNTS[short]}')
        lines.append(f'const char *const d3d12_umd_{short}_slot_names[{len(fields)}] = {{')
        lines += [f'    "{f["name"]}",' for f in fields]
        lines.append('};')
        lines.append(f'static volatile LONG {short}_stub_hits[{len(fields)}];')
        lines.append('')
        for i, f in enumerate(fields):
            sig = signature(f)
            if sig is None:
                # void* placeholders (pfnUnused): any stub with no arguments will do.
                sig = ('void', [])
            ret, params = sig
            args = ', '.join(declare(p, f'a{j}') for j, p in enumerate(params)) or 'void'
            lines.append(f'static {ret} APIENTRY stub_{short}_{f["name"]}({args})')
            lines.append('{')
            for j in range(len(params)):
                lines.append(f'    (void)a{j};')
            lines.append(f'    d3d12_umd_stub_hit("{short}", {i}, "{f["name"]}", &{short}_stub_hits[{i}]);')
            value = default_return(ret)
            if value is not None:
                lines.append(f'    return {value};')
            lines.append('}')
            lines.append('')
        lines.append(f'void d3d12_umd_stub_fill_{short}({table} *t)')
        lines.append('{')
        for f in fields:
            if signature(f) is None:
                lines.append(f'    t->{f["name"]} = (void *)stub_{short}_{f["name"]};')
            else:
                lines.append(f'    t->{f["name"]} = stub_{short}_{f["name"]};')
        lines.append('}')
        lines.append('')
    with open(a.output, 'w') as fp:
        fp.write('\n'.join(lines))


if __name__ == '__main__':
    main()
